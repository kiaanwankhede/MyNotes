#!/usr/bin/env python3
"""Source ledger for a book: which course files were used, and what changed since.

Usage:
  python3 -I build/sources.py snapshot <book_id> <course_repo_dir>
      Record every tracked file in the course repo (git blob hash), whether a chapter
      links to it, and how deeply it was reviewed. Writes books/<book>/sources.json
      and books/<book>/COVERAGE.md.
  python3 -I build/sources.py check <book_id> <course_repo_dir>
      Compare a fresh copy of the course repo against the ledger and report files that
      are new, changed or removed, and which chapters cite the changed files.

Review depth comes from books/<book>/review_levels.json (longest matching prefix wins):
  read       read in full or close to it
  skimmed    scanned, extracted or partly read
  not_read   listed but not read
Files matching IGNORE rules (lock files, logs, databases, archives) are marked ignored.
"""
import datetime
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

IGNORE = [
    (r"(^|/)(uv\.lock|package-lock\.json|bun\.lock)$", "dependency lock file"),
    (r"(^|/)\.(gitignore|gitattributes|python-version|dockerignore)$", "tooling config"),
    (r"\.(log|db|zip)$", "log, database or archive"),
    (r"(^|/)__init__\.py$", "empty package marker"),
    (r"(^|/)pyproject\.toml$", "project metadata"),
    (r"(^|/)frontend/(?!src/)", "frontend build config"),
]


def git(course, *args):
    return subprocess.run(["git", "-C", course, *args], capture_output=True, text=True, check=True).stdout


def tracked(course):
    """Return {path: blob_sha} for every tracked file."""
    out = git(course, "ls-files", "-s", "-z")
    files = {}
    for rec in out.split("\0"):
        if not rec:
            continue
        meta, path = rec.split("\t", 1)
        files[path] = meta.split()[1]
    return files


def ignore_reason(path):
    for pat, why in IGNORE:
        if re.search(pat, path):
            return why
    return None


def load_json(path, default):
    return json.load(open(path, encoding="utf-8")) if os.path.exists(path) else default


def chapter_citations(book_dir):
    """Map chapter file -> (exact paths, tree prefixes) that its source links point to."""
    cites = {}
    cdir = os.path.join(book_dir, "chapters")
    for name in sorted(os.listdir(cdir)):
        if not name.endswith(".md"):
            continue
        text = open(os.path.join(cdir, name), encoding="utf-8").read()
        exact, trees = set(), set()
        for kind, p in re.findall(r"\{\{(src|tree):(.+?)\}\}", text):
            (exact if kind == "src" else trees).add(p.strip())
        cites[name[:-3]] = (exact, trees)
    return cites


def cited_by(path, cites):
    hits = []
    for ch, (exact, trees) in cites.items():
        if path in exact or any(path == t or path.startswith(t.rstrip("/") + "/") for t in trees):
            hits.append(ch)
    return hits


def level_for(path, levels):
    best, lvl = -1, "not_read"
    for rule in levels:
        pre = rule["prefix"]
        if path.startswith(pre) and len(pre) > best:
            best, lvl = len(pre), rule["level"]
    return lvl


def snapshot(book, course):
    book_dir = os.path.join(ROOT, "books", book)
    levels = load_json(os.path.join(book_dir, "review_levels.json"), [])
    cites = chapter_citations(book_dir)
    files = tracked(course)
    manifest = {
        "course_repo": "https://github.com/mayank953/Live-Class-2026",
        "commit": git(course, "rev-parse", "HEAD").strip(),
        "generated": datetime.date.today().isoformat(),
        "files": {},
    }
    for path, blob in sorted(files.items()):
        why = ignore_reason(path)
        entry = {"blob": blob, "cited_in": cited_by(path, cites)}
        if why:
            entry["status"] = "ignored"
            entry["reason"] = why
        else:
            entry["status"] = level_for(path, levels)
        manifest["files"][path] = entry
    json.dump(manifest, open(os.path.join(book_dir, "sources.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    write_coverage(book_dir, manifest)
    summary(manifest)


def summary(manifest):
    counts = {}
    for e in manifest["files"].values():
        counts[e["status"]] = counts.get(e["status"], 0) + 1
    cited = sum(1 for e in manifest["files"].values() if e["cited_in"])
    print("course commit %s, %d files" % (manifest["commit"][:7], len(manifest["files"])))
    print("  " + ", ".join("%s: %d" % kv for kv in sorted(counts.items())))
    print("  cited by at least one chapter: %d" % cited)


def write_coverage(book_dir, manifest):
    files = manifest["files"]
    by = {}
    for p, e in files.items():
        by.setdefault(e["status"], []).append(p)
    lines = [
        "# Source coverage",
        "",
        "Generated by `build/sources.py` on %s from the course repo at commit `%s`." % (manifest["generated"], manifest["commit"][:7]),
        "",
        "| Status | Files | Meaning |",
        "| --- | ---: | --- |",
        "| read | %d | Read in full or close to it |" % len(by.get("read", [])),
        "| skimmed | %d | Scanned, extracted or partly read |" % len(by.get("skimmed", [])),
        "| not_read | %d | Listed but not read. Candidates for a deeper pass |" % len(by.get("not_read", [])),
        "| ignored | %d | Lock files, logs, databases, archives and tooling config |" % len(by.get("ignored", [])),
        "",
        "A file is **cited** when a chapter links to it under Sources. Citing is not the same as reading in full: use the status column.",
        "",
    ]
    for status, title in (("not_read", "Not read yet (cited ones first)"), ("skimmed", "Skimmed"), ("read", "Read")):
        items = sorted(by.get(status, []), key=lambda p: (not files[p]["cited_in"], p))
        lines += ["## %s (%d)" % (title, len(items)), ""]
        for p in items:
            ch = files[p]["cited_in"]
            lines.append("- `%s`%s" % (p, (" (cited in %s)" % ", ".join(ch)) if ch else ""))
        lines.append("")
    open(os.path.join(book_dir, "COVERAGE.md"), "w", encoding="utf-8").write("\n".join(lines))


def check(book, course):
    book_dir = os.path.join(ROOT, "books", book)
    manifest = json.load(open(os.path.join(book_dir, "sources.json"), encoding="utf-8"))
    old = manifest["files"]
    now = tracked(course)
    cites = chapter_citations(book_dir)
    new = sorted(p for p in now if p not in old)
    gone = sorted(p for p in old if p not in now)
    changed = sorted(p for p in now if p in old and old[p]["blob"] != now[p])
    print("ledger commit %s, course now at %s" % (manifest["commit"][:7], git(course, "rev-parse", "HEAD").strip()[:7]))
    print("NEW files (%d):" % len(new))
    for p in new:
        print("  + %s%s" % (p, "  [ignored: %s]" % ignore_reason(p) if ignore_reason(p) else ""))
    print("CHANGED files (%d):" % len(changed))
    for p in changed:
        ch = cited_by(p, cites)
        print("  ~ %s%s" % (p, "  -> update chapters: %s" % ", ".join(ch) if ch else ""))
    print("REMOVED files (%d):" % len(gone))
    for p in gone:
        print("  - %s" % p)
    todo = [p for p, e in old.items() if e["status"] == "not_read" and p in now]
    print("Still not read from the earlier snapshot: %d (see COVERAGE.md)" % len(todo))


def main():
    if len(sys.argv) != 4 or sys.argv[1] not in ("snapshot", "check"):
        print(__doc__)
        sys.exit(2)
    cmd, book, course = sys.argv[1], sys.argv[2], os.path.abspath(sys.argv[3])
    (snapshot if cmd == "snapshot" else check)(book, course)


if __name__ == "__main__":
    main()
